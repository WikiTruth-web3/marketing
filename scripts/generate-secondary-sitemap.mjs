/**
 * Post-build script: generate sitemap files for the secondary domain
 * by copying the primary sitemap and replacing the domain name.
 *
 * Usage: node scripts/generate-secondary-sitemap.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
let distDir = path.resolve(__dirname, '../dist');

// Cloudflare adapter in server mode outputs static files to dist/client
if (fs.existsSync(path.join(distDir, 'client'))) {
  distDir = path.join(distDir, 'client');
}

const PRIMARY_DOMAIN = 'https://evidencemarket.org';
const SECONDARY_DOMAIN = 'https://wikitruth.xyz';

// Find all sitemap files generated by @astrojs/sitemap
const sitemapFiles = fs.readdirSync(distDir).filter(f => f.startsWith('sitemap-'));

if (sitemapFiles.length === 0) {
  console.error('No sitemap files found in dist/. Make sure astro build ran first.');
  process.exit(1);
}

for (const file of sitemapFiles) {
  const srcPath = path.join(distDir, file);
  // Rename: sitemap-index.xml -> sitemap-wikitruth-index.xml
  //         sitemap-0.xml     -> sitemap-wikitruth-0.xml
  const newName = file.replace('sitemap-', 'sitemap-wikitruth-');
  const destPath = path.join(distDir, newName);

  let content = fs.readFileSync(srcPath, 'utf-8');
  // Replace domain
  content = content.replaceAll(PRIMARY_DOMAIN, SECONDARY_DOMAIN);
  // Fix internal sitemap references in the index file (e.g. sitemap-0.xml -> sitemap-wikitruth-0.xml)
  if (file === 'sitemap-index.xml') {
    content = content.replaceAll('/sitemap-', '/sitemap-wikitruth-');
  }

  fs.writeFileSync(destPath, content, 'utf-8');
  console.log(`Generated ${newName}`);
}

console.log('Secondary domain sitemaps generated successfully.');
